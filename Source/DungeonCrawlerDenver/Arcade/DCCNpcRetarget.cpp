// DCC.NpcRetarget (2026-11-14): editor-only. Gives the NPC Forge people (Tools/npc_forge.py -> Tools/import_npcs.py)
// the mannequin's animations.
//
// The NPCs are MakeHuman bodies on MPFB's "game_engine" rig: UE4 mannequin bone names, but not the UE5 mannequin's
// skeleton, so Manny's clips cannot play on them directly. This builds the retarget in code (there is no MCP tool for
// IK Rigs), run once from the command line:
//   UnrealEditor.exe <project> -ExecCmds="DCC.NpcRetarget"
//   1. IK Rigs for Manny and for the shared NPC skeleton, both auto-characterized (the engine recognises both layouts).
//   2. A retargeter Manny -> NPC with the default op stack, chains auto-mapped, the NPC's pose auto-aligned to Manny's.
//   3. A batch retarget of the clips the NPCs need into /Game/DCC/Characters/NPCs/Anims (NPC_ prefix), then saves.
// Re-running rebuilds the rigs and overwrites the clips.

